/**
 * Реестр захватов жеста на карте.
 *
 * Модули, которые сами обрабатывают перетаскивание по карте (drawTools во
 * время правки вершины), берут захват на время жеста, а модули, которые
 * превращают перетаскивание в собственное действие (singleFingerRotation
 * поворачивает карту), при активном захвате не вмешиваются.
 *
 * Реестр в core вместо прямой связи модулей: ни один из них не знает про
 * другой, а порядок включения и выключения в настройках роли не играет.
 * Захватов может быть несколько одновременно, поэтому считаются владельцы,
 * а не булев флаг: снятие одного захвата не отпускает жест, пока держит
 * второй.
 */
const gestureOwners = new Set<symbol>();

/** Захватывает жест на карте. Возвращает функцию снятия захвата. */
export function lockMapGesture(): () => void {
  const owner = Symbol('mapGesture');
  gestureOwners.add(owner);
  return () => {
    gestureOwners.delete(owner);
  };
}

export function isMapGestureLocked(): boolean {
  return gestureOwners.size > 0;
}
